export default async function LocaleLayout({
  children,
  params,
}: {
  children: ReactNode
  params: Promise<{ locale: string }>
}) {
  const { locale } = await params
  if (!(locales as readonly string[]).includes(locale)) notFound()
  setRequestLocale(locale)

  const messages = await getMessages()

  // Site-wide Organization schema — surfaces in Google's knowledge panel
  // and lets crawlers tie cross-page entities (Product, FAQPage) back to
  // the same legal entity. Locale-independent; one block per page is enough.
  const organizationLd = {
    "@context": "https://schema.org",
    "@type": "Organization",
    name: "VettGuard",
    url: siteOrigin,
    logo: `${siteOrigin}/icon`,
    sameAs: [
      "https://twitter.com/vettguardhq",
      "https://www.linkedin.com/company/vettguard",
    ],
    contactPoint: [
      {
        "@type": "ContactPoint",
        contactType: "customer support",
        email: "support@vettguard.com",
        availableLanguage: ["English", "Uzbek", "Russian", "Spanish", "Turkish", "Ukrainian"],
      },
    ],
  }

  return (
    <html lang={locale} suppressHydrationWarning>
      <body>
        <JsonLd data={organizationLd} />
        <NextIntlClientProvider locale={locale} messages={messages}>
          <ThemeProvider>{children}</ThemeProvider>
        </NextIntlClientProvider>
      </body>
    </html>
  )
}
