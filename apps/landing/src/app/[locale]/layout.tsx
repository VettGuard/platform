export function generateStaticParams() {
  return locales.map((locale) => ({ locale }))
}

export async function generateMetadata({
  params,
}: {
  params: Promise<{ locale: string }>
}): Promise<Metadata> {
  const { locale } = await params
  const copy = localizedCopy[locale] ?? EN_COPY
  const path = locale === "en" ? "/" : `/${locale}`

  return {
    title: copy.title,
    description: copy.description,
    metadataBase: new URL(siteOrigin),
    alternates: {
      canonical: path,
      languages: Object.fromEntries(
        locales.map((l) => [l, l === "en" ? "/" : `/${l}`]),
      ),
    },
    openGraph: {
      type: "website",
      url: `${siteOrigin}${path}`,
      siteName: "VettGuard",
      title: copy.title,
      description: copy.description,
      locale,
      // Explicit absolute URL for OG: the file-based opengraph-image.tsx at
      // app/ root would otherwise be auto-injected as `/en/opengraph-image`
      // (the locale segment confuses Next's path resolver), which would
      // 404. Pinning it to `/opengraph-image` keeps it crawler-friendly.
      images: [
        {
          url: `${siteOrigin}/opengraph-image`,
          width: 1200,
          height: 630,
          alt: "VettGuard — AI dispatch copilot",
        },
      ],
    },
    twitter: {
      card: "summary_large_image",
      title: copy.title,
      description: copy.description,
      images: [`${siteOrigin}/opengraph-image`],
      creator: "@vettguardhq",
    },
    // Favicon is generated by app/icon.tsx — Next.js wires the <link> automatically.
    robots: { index: true, follow: true },
  }
}

