"""Prometheus metrics for ai-gateway.

Exposed at ``GET /metrics`` for Prometheus to scrape. The kube-prometheus-stack
ServiceMonitor (or PodMonitor) is wired in infra/k3s/argocd/apps/observability.

Cardinality note: ``tenant_id`` is a label on token-usage counters. We expect
≤a few thousand tenants — well below Prom's 100k series ceiling. If that
explodes, drop the label and rely on per-tenant accounting in the daily-budget
table instead.
"""

from __future__ import annotations

from prometheus_client import (
    CONTENT_TYPE_LATEST,
    CollectorRegistry,
    Counter,
    Histogram,
    generate_latest,
)

# Single shared registry — easier to reset in tests than the default global.
registry = CollectorRegistry()

requests_total = Counter(
    "ai_gateway_requests_total",
    "AI requests by route, model, and outcome.",
    labelnames=("route", "model", "outcome"),
    registry=registry,
)

request_latency_seconds = Histogram(
    "ai_gateway_request_latency_seconds",
    "End-to-end request latency, including upstream Anthropic call.",
    labelnames=("route", "model"),
    registry=registry,
    buckets=(0.1, 0.25, 0.5, 1, 2, 4, 8, 16, 32, 60),
)

tokens_input_total = Counter(
    "ai_gateway_tokens_input_total",
    "Input tokens (excluding cache hits).",
    labelnames=("tenant_id", "model", "route"),
    registry=registry,
)

tokens_output_total = Counter(
    "ai_gateway_tokens_output_total",
    "Output tokens generated by Claude.",
    labelnames=("tenant_id", "model", "route"),
    registry=registry,
)

tokens_cache_read_total = Counter(
    "ai_gateway_tokens_cache_read_total",
    "Tokens served from Anthropic's prompt cache (the cost saver). "
    "Grafana panel: cache_read / (cache_read + input) → cache hit rate.",
    labelnames=("tenant_id", "model", "route"),
    registry=registry,
)

tokens_cache_creation_total = Counter(
    "ai_gateway_tokens_cache_creation_total",
    "Tokens billed at 1.25x to seed a new cache entry. Should be low.",
    labelnames=("tenant_id", "model", "route"),
    registry=registry,
)

budget_rejections_total = Counter(
    "ai_gateway_budget_rejections_total",
    "Requests rejected because the tenant exceeded its daily token budget.",
    labelnames=("tenant_id",),
    registry=registry,
)


def render() -> tuple[bytes, str]:
    """Return ``(payload, content_type)`` for the /metrics endpoint."""
    return generate_latest(registry), CONTENT_TYPE_LATEST
